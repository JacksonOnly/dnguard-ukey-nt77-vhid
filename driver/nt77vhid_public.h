#ifndef NT77VHID_PUBLIC_H
#define NT77VHID_PUBLIC_H

#ifdef _KERNEL_MODE
#include <ntddk.h>
#else
#include <windows.h>
#include <stdint.h>
#endif

#define NT77VHID_CONTROL_PATH L"\\\\.\\Nt77VhidControl"
#define NT77VHID_SERIAL_SIZE 32u
#define NT77VHID_LOGIN_DIGEST_SIZE 16u
#define NT77VHID_HARDWARE_ID_SIZE 24u
#define NT77VHID_STORAGE_SIZE 1024u

#define IOCTL_NT77_SET_SERIAL \
    CTL_CODE(FILE_DEVICE_UNKNOWN, 0x800, METHOD_BUFFERED, FILE_WRITE_DATA)
#define IOCTL_NT77_SET_LOGIN_MD5 \
    CTL_CODE(FILE_DEVICE_UNKNOWN, 0x801, METHOD_BUFFERED, FILE_WRITE_DATA)
#define IOCTL_NT77_SET_HARDWARE_ID \
    CTL_CODE(FILE_DEVICE_UNKNOWN, 0x802, METHOD_BUFFERED, FILE_WRITE_DATA)
#define IOCTL_NT77_WRITE_STORAGE \
    CTL_CODE(FILE_DEVICE_UNKNOWN, 0x803, METHOD_BUFFERED, FILE_WRITE_DATA)
#define IOCTL_NT77_CLEAR_STORAGE \
    CTL_CODE(FILE_DEVICE_UNKNOWN, 0x804, METHOD_BUFFERED, FILE_WRITE_DATA)
#define IOCTL_NT77_QUERY_STATUS \
    CTL_CODE(FILE_DEVICE_UNKNOWN, 0x805, METHOD_BUFFERED, FILE_READ_DATA)

typedef struct NT77VHID_SERIAL_CONFIG {
    UCHAR Bytes[NT77VHID_SERIAL_SIZE];
} NT77VHID_SERIAL_CONFIG;

typedef struct NT77VHID_LOGIN_CONFIG {
    UCHAR Digest[NT77VHID_LOGIN_DIGEST_SIZE];
} NT77VHID_LOGIN_CONFIG;

typedef struct NT77VHID_HARDWARE_ID_CONFIG {
    UCHAR Bytes[NT77VHID_HARDWARE_ID_SIZE];
} NT77VHID_HARDWARE_ID_CONFIG;

typedef struct NT77VHID_STORAGE_WRITE {
    USHORT Offset;
    USHORT Length;
    UCHAR Data[1];
} NT77VHID_STORAGE_WRITE;

typedef struct NT77VHID_STATUS {
    UCHAR SerialConfigured;
    UCHAR LoginConfigured;
    UCHAR HardwareIdConfigured;
    UCHAR LoggedIn;
    UCHAR Serial[NT77VHID_SERIAL_SIZE];
    UCHAR HardwareId[NT77VHID_HARDWARE_ID_SIZE];
} NT77VHID_STATUS;

#endif
